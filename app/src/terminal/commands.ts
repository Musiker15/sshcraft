// Commands SSHCraft knows with their subcommands and options, for completion without AI. Not
// translated: these are what the user types.

export type CommandSpec = { sub?: Record<string, CommandSpec>; flags?: string[] };

const leaf: CommandSpec = {};
const subs = (names: string[], flags?: string[]): Record<string, CommandSpec> =>
  Object.fromEntries(names.map((n) => [n, flags ? { flags } : leaf]));

const packageManager = (verbs: string[], flags: string[]): CommandSpec => ({ sub: subs(verbs), flags });

